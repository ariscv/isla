/// For now, we assume that we only deal with 64-bit architectures.
pub type Address = u64;

pub trait CustomRegion<B> {
    fn read(
        &self,
        read_kind: Val<B>,
        address: Address,
        bytes: u32,
        solver: &mut Solver<B>,
        tag: bool,
    ) -> Result<Val<B>, ExecError>;

    fn write(
        &mut self,
        write_kind: Val<B>,
        address: Address,
        data: Val<B>,
        solver: &mut Solver<B>,
        tag: Option<Val<B>>,
    ) -> Result<Val<B>, ExecError>;

    fn initial_value(&self, address: Address, bytes: u32) -> Option<B>;

    /// Return a static string denoting the 'kind' or 'name' of memory
    /// this custom region is representing, e.g. "device" or
    /// "page_table". This information is only used for display
    /// purposes, and has no semantic meaning.
    fn region_name(&self) -> &'static str;

    /// Trait objects (`dyn T`) are in general not cloneable, so we
    /// require a method that allows us to implement clone ourselves
    /// for types containing `Box<dyn T>`. The implementation will
    /// nearly always be just `Box::new(self.clone())`.
    fn clone_dyn(&self) -> Box<dyn Send + Sync + CustomRegion<B>>;
}

pub enum Region<B> {
    /// A region with a symbolic value constrained by a symbolic
    /// variable generated by an arbitrary function. The region should
    /// return a bitvector variable representing the whole region, so
    /// in practice this should be used for small regions of memory.
    Constrained(Range<Address>, Arc<dyn Send + Sync + Fn(&mut Solver<B>) -> Sym>),
    /// A region of arbitrary symbolic locations
    Symbolic(Range<Address>),
    /// A read only region of arbitrary symbolic locations intended for code
    SymbolicCode(Range<Address>),
    /// A region of concrete read-only memory
    Concrete(Range<Address>, HashMap<Address, u8>),
    /// 判死区域（W9 语义）：声明"这一段不关心"。任何访问（读或写，符号或
    /// 具体地址）与该区域重叠即判死该执行路径——具体地址直接 BadRead/
    /// BadWrite；符号地址由回调追加 NOT(与判死区域并集重叠) 约束，与路径
    /// 既有断言联立 Unsat 时经 W7 机制立即判死。区域内没有任何内容语义。
    Excluded(Range<Address>),
    /// A custom region
    Custom(Range<Address>, Box<dyn Send + Sync + CustomRegion<B>>),
}

impl<B> Clone for Region<B> {
    fn clone(&self) -> Self {
        use Region::*;
        match self {
            Constrained(r, contents) => Constrained(r.clone(), contents.clone()),
            Symbolic(r) => Symbolic(r.clone()),
            SymbolicCode(r) => SymbolicCode(r.clone()),
            Concrete(r, contents) => Concrete(r.clone(), contents.clone()),
            Excluded(r) => Excluded(r.clone()),
            Custom(r, contents) => Custom(r.clone(), contents.clone_dyn()),
        }
    }
}

pub enum SmtKind {
    ReadData,
    ReadInstr,
    WriteData,
}

impl<B> fmt::Debug for Region<B> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        use Region::*;
        match self {
            Constrained(r, _) => write!(f, "Constrained({:?}, <closure>)", r),
            Symbolic(r) => write!(f, "Symbolic({:?})", r),
            SymbolicCode(r) => write!(f, "SymbolicCode({:?})", r),
            Concrete(r, locs) => write!(f, "Concrete({:?}, {:?})", r, locs),
            Excluded(r) => write!(f, "Excluded({:?})", r),
            Custom(r, _) => write!(f, "Custom({:?}, <trait object>)", r),
        }
    }
}

impl<B> Region<B> {
    fn region_name(&self) -> &'static str {
        match self {
            Region::Constrained(_, _) => "constrained",
            Region::Symbolic(_) => "symbolic",
            Region::SymbolicCode(_) => "symbolic code",
            Region::Concrete(_, _) => "concrete",
            Region::Excluded(_) => "excluded",
            Region::Custom(_, contents) => contents.region_name(),
        }
    }

    pub fn region_range(&self) -> &Range<Address> {
        match self {
            Region::Constrained(r, _) => r,
            Region::Symbolic(r) => r,
            Region::SymbolicCode(r) => r,
            Region::Concrete(r, _) => r,
            Region::Excluded(r) => r,
            Region::Custom(r, _) => r,
        }
    }
}

// Optional client interface.  At the time of writing this is only
// used by the test generation to enforce sequential memory, so we
// jump through a few hoops to avoid other clients seeing it.  If it
// was used more generally then it would be better to parametrise the
// Memory struct instead.

pub trait MemoryCallbacks<B>: fmt::Debug + MemoryCallbacksClone<B> + Send + Sync {
    /// 回调若会用区域约束排除非符号内存的写入，可直接处理尚未收窄的符号地址。
    /// Custom 区域始终先经 Memory 检查，唯一地址调用设备，否则拆分重试。
    /// 默认仍由 Memory 提前检查可能与具体区域重叠的地址。
    fn constrains_symbolic_writes(&self) -> bool {
        false
    }

    /// 回调能自行处理符号读地址约束时，可直接处理尚未收窄的符号地址。
    /// 回调须保留已知初值；Custom 始终经专属分派，Constrained 保留整区域读取检查。
    /// 需要接管普通具体读时另启用 handles_concrete_reads。
    /// 默认仍由 Memory 先检查具体区域重叠，必要时请求地址拆分。
    fn constrains_symbolic_reads(&self) -> bool {
        false
    }

    /// 回调维护 Concrete／Constrained 初值和更新时，普通具体读也经过同一份内存状态。
    fn handles_concrete_reads(&self) -> bool {
        false
    }

    /// 符号读回调。返回值表示本次调用是否向 solver 追加了**读地址约束**
    /// （W9 起如数组内存模型的判死区域 NOT 链）：为真时 `read_symbolic` 会在
    /// 回调返回后立即检查可满足性，约束与路径上更早的断言矛盾（例如模型侧
    /// PMA/PMP 分支已把地址钉进判死区域）时直接以 BadRead 判死路径，而不是
    /// 把 Unsat 留到路径终值查询。
    #[allow(clippy::too_many_arguments)]
    fn symbolic_read(
        &self,
        regions: &[Region<B>],
        solver: &mut Solver<B>,
        value: &Val<B>,
        read_kind: &Val<B>,
        address: &Val<B>,
        bytes: u32,
        tag: &Option<Val<B>>,
        opts: &ReadOpts,
    ) -> bool;
    /// 符号写回调。返回值语义与 `symbolic_read` 对称：为真表示追加了写地址
    /// 约束，`write_symbolic` 随后立即做可满足性检查，矛盾时以 BadWrite 判死。
    #[allow(clippy::too_many_arguments)]
    fn symbolic_write(
        &mut self,
        regions: &[Region<B>],
        solver: &mut Solver<B>,
        value: Sym,
        write_kind: &Val<B>,
        address: &Val<B>,
        data: &Val<B>,
        bytes: u32,
        tag: &Option<Val<B>>,
        opts: &WriteOpts,
    ) -> bool;
    fn symbolic_write_tag(
        &mut self,
        regions: &[Region<B>],
        solver: &mut Solver<B>,
        value: Sym,
        write_kind: &Val<B>,
        address: &Val<B>,
        tag: &Val<B>,
    );
}

pub trait MemoryCallbacksClone<B> {
    fn clone_box(&self) -> Box<dyn MemoryCallbacks<B>>;
}

impl<B, T> MemoryCallbacksClone<B> for T
where
    T: 'static + MemoryCallbacks<B> + Clone,
{
    fn clone_box(&self) -> Box<dyn MemoryCallbacks<B>> {
        Box::new(self.clone())
    }
}

impl<B> Clone for Box<dyn MemoryCallbacks<B>> {
    fn clone(&self) -> Box<dyn MemoryCallbacks<B>> {
        self.clone_box()
    }
}

fn make_bv_bit_pair<B>(left: Val<B>, right: Val<B>) -> Val<B> {
    let mut fields = HashMap::default();
    fields.insert(ir::BV_BIT_LEFT, left);
    fields.insert(ir::BV_BIT_RIGHT, right);
    Val::Struct(fields)
}

#[derive(Clone, Debug, Default)]
pub struct Memory<B> {
    regions: Vec<Region<B>>,
    client_info: Option<Box<dyn MemoryCallbacks<B>>>,
}

static DEFAULT_REGION_NAME: &str = "default";

enum Overlap {
    Unique(u64),
    NoOverlap,
}

impl<B: BV> Memory<B> {
    pub fn new() -> Self {
        Memory { regions: Vec::new(), client_info: None }
    }

    pub fn regions(&self) -> &[Region<B>] {
        &self.regions
    }

    pub fn region_name_at(&self, addr: Address) -> &'static str {
        for region in &self.regions {
            if region.region_range().contains(&addr) {
                return region.region_name();
            }
        }
        DEFAULT_REGION_NAME
    }

    pub fn log(&self) {
        for region in &self.regions {
            match region {
                Region::Constrained(range, _) => {
                    log!(log::MEMORY, &format!("Memory range: [0x{:x}, 0x{:x}) constrained", range.start, range.end))
                }
                Region::Symbolic(range) => {
                    log!(log::MEMORY, &format!("Memory range: [0x{:x}, 0x{:x}) symbolic", range.start, range.end))
                }
                Region::SymbolicCode(range) => {
                    log!(log::MEMORY, &format!("Memory range: [0x{:x}, 0x{:x}) symbolic code", range.start, range.end))
                }
                Region::Concrete(range, _) => {
                    log!(log::MEMORY, &format!("Memory range: [0x{:x}, 0x{:x}) concrete", range.start, range.end))
                }
                Region::Excluded(range) => {
                    log!(log::MEMORY, &format!("Memory range: [0x{:x}, 0x{:x}) excluded", range.start, range.end))
                }
                Region::Custom(range, contents) => log!(
                    log::MEMORY,
                    &format!(
                        "Memory range: [0x{:x}, 0x{:x}) custom {}",
                        range.start,
                        range.end,
                        contents.region_name()
                    )
                ),
            }
        }
    }

    pub fn in_custom_region(&self, addr: Address) -> Option<&dyn CustomRegion<B>> {
        for region in &self.regions {
            match region {
                Region::Custom(range, mem) if range.contains(&addr) => return Some(mem.as_ref()),
                _ => (),
            }
        }
        None
    }

    pub fn add_region(&mut self, region: Region<B>) {
        self.regions.push(region)
    }

    pub fn add_symbolic_region(&mut self, range: Range<Address>) {
        self.regions.push(Region::Symbolic(range))
    }

    pub fn add_symbolic_code_region(&mut self, range: Range<Address>) {
        self.regions.push(Region::SymbolicCode(range))
    }

    pub fn add_concrete_region(&mut self, range: Range<Address>, contents: HashMap<Address, u8>) {
        self.regions.push(Region::Concrete(range, contents))
    }

    pub fn add_excluded_region(&mut self, range: Range<Address>) {
        self.regions.push(Region::Excluded(range))
    }

    pub fn add_zero_region(&mut self, range: Range<Address>) {
        self.regions.push(Region::Concrete(range, HashMap::new()))
    }

    pub fn set_client_info(&mut self, info: Box<dyn MemoryCallbacks<B>>) {
        self.client_info = Some(info);
    }

    pub fn write_byte(&mut self, address: Address, byte: u8) {
        for region in &mut self.regions {
            match region {
                Region::Concrete(range, contents) if range.contains(&address) => {
                    contents.insert(address, byte);
                    return;
                }
                _ => (),
            }
        }
        self.regions.push(Region::Concrete(address..address, vec![(address, byte)].into_iter().collect()))
    }

    fn read_initial_byte(&self, address: Address) -> Result<u8, ExecError> {
        use Region::*;
        for region in &self.regions {
            match region {
                Constrained(range, _) | Symbolic(range) | SymbolicCode(range) if range.contains(&address) => {
                    return Err(ExecError::BadRead("Symbolic initial byte"))
                }
                Concrete(range, contents) if range.contains(&address) => {
                    return Ok(contents.get(&address).copied().unwrap_or(0))
                }
                Excluded(range) if range.contains(&address) => return Err(ExecError::BadRead("Excluded initial byte")),
                Custom(range, contents) if range.contains(&address) => {
                    return contents
                        .initial_value(address, 1)
                        .map(B::lower_u8)
                        .ok_or(ExecError::BadRead("Read of initial byte from custom region failed"))
                }
                _ => (),
            }
        }
        Err(ExecError::BadRead("Symbolic initial byte (no region)"))
    }

    pub fn read_initial(&self, address: Address, bytes: u32) -> Result<Val<B>, ExecError> {
        let mut byte_vec: Vec<u8> = Vec::with_capacity(bytes as usize);
        for i in address..(address + u64::from(bytes)) {
            byte_vec.push(self.read_initial_byte(i)?)
        }

        reverse_endianness(&mut byte_vec);

        if byte_vec.len() <= 8 {
            Ok(Val::Bits(B::from_bytes(&byte_vec)))
        } else {
            Err(ExecError::BadRead("Initial read greater than 8 bytes"))
        }
    }

    // 按调用方选择的区域检查重叠；回调只能接管普通内存，专属区域仍须具体分派。
    fn check_concrete_overlap(
        &self,
        address: Sym,
        bytes: u32,
        error: ExecError,
        include_region: impl Fn(&Region<B>) -> bool,
        solver: &mut Solver<B>,
    ) -> Result<Overlap, ExecError> {
        use Exp::*;
        use SmtResult::*;

        let mut region_constraints = Vec::new();

        let addr_size = solver.length(address).unwrap_or_else(|| panic!("address is not a bitvector"));
        let cmp_size = 64;
        // 与具体地址的 lower_u64() 一致，区域始终在 u64 地址空间中分派。
        let addr_exp = if addr_size > cmp_size {
            Extract(63, 0, Box::new(Var(address)))
        } else if addr_size < cmp_size {
            ZeroExtend(cmp_size - addr_size, Box::new(Var(address)))
        } else {
            Var(address)
        };

        let mut unmatched = Bool(true);
        for region in &self.regions {
            if matches!(region, Region::Excluded(_)) {
                continue;
            }
            let Range { start, end } = region.region_range();
            let in_region = And(
                Box::new(Bvule(Box::new(bits64(*start, cmp_size)), Box::new(addr_exp.clone()))),
                Box::new(Bvult(Box::new(addr_exp.clone()), Box::new(bits64(*end, cmp_size)))),
            );
            if include_region(region) {
                region_constraints.push(And(Box::new(unmatched.clone()), Box::new(in_region.clone())));
            }
            // 所有前序区域都参与遮蔽，不能只累计需要专属分派的区域。
            unmatched = And(Box::new(unmatched), Box::new(Not(Box::new(in_region))));
        }

        // 自约束回调负责排除区域时不请求拆分；其余调用方检查全部实际访问字节。
        if self.regions.iter().any(|region| matches!(region, Region::Excluded(_)) && include_region(region)) {
            let allowed = smt_excluded_constraint(&self.regions, &Var(address), bytes, solver)
                .expect("已选中的排除区域必须生成约束");
            // 无合法候选时无需拆分地址，交给符号读写追加排除约束并返回访问错误。
            if self.client_info.is_none() && solver.check_sat_with(&allowed, SourceLoc::unknown()).is_unsat()? {
                return Ok(Overlap::NoOverlap);
            }
            region_constraints.push(Not(Box::new(allowed)));
        }

        if let Some(r) = region_constraints.pop() {
            let constraint = region_constraints.drain(..).fold(r, |r1, r2| Or(Box::new(r1), Box::new(r2)));
            match solver.check_sat_with(&constraint, SourceLoc::unknown()) {
                Sat => {
                    let sat_address = {
                        let mut model = Model::new(solver);
                        model.set_complete_model(true);
                        let ModelVal::Exp(Bits64(sat_address)) = model.get_exp(&addr_exp)? else {
                            panic!("64 位地址投影的模型值必须是 Bits64");
                        };
                        sat_address.lower_u64()
                    };
                    // Check if the satisifiable address in the
                    // concrete region is actually unique, in which
                    // case the caller could choose to treat it as a
                    // concrete value.
                    let uniqueness_constraint = Neq(Box::new(addr_exp), Box::new(bits64(sat_address, cmp_size)));
                    match solver.check_sat_with(&uniqueness_constraint, SourceLoc::unknown()) {
                        Unsat => Ok(Overlap::Unique(sat_address)),
                        Unknown => Err(ExecError::Z3Unknown),
                        Error(error) => Err(ExecError::Smt(error)),
                        Sat => {
                            log!(log::MEMORY, &format!("Overlapping satisfiable address: {:x}", sat_address));
                            probe::taint_info(log::MEMORY, address, None, solver);
                            Err(error)
                        }
                    }
                }
                Unknown => Err(ExecError::Z3Unknown),
                Error(error) => Err(ExecError::Smt(error)),
                Unsat => Ok(Overlap::NoOverlap),
            }
        } else {
            // There are no concrete regions
            Ok(Overlap::NoOverlap)
        }
    }

    /// Read from the memory region determined by the address. If the address is symbolic the read
    /// value is always also symbolic. The number of bytes must be concrete otherwise will return a
    /// SymbolicLength error.
    ///
    /// # Panics
    ///
    /// Panics if the number of bytes to read is concrete but does not fit
    /// in a u32, which should never be the case.
    pub fn read(
        &self,
        read_kind: Val<B>,
        address: Val<B>,
        bytes: Val<B>,
        solver: &mut Solver<B>,
        tag: bool,
        opts: ReadOpts,
    ) -> Result<Val<B>, ExecError> {
        log!(log::MEMORY, &format!("Read: {:?} {:?} {:?} {:?}", read_kind, address, bytes, tag));

        if let Val::I128(bytes) = bytes.widen_int() {
            let bytes = u32::try_from(bytes).expect("Bytes did not fit in u32 in memory read");

            match address {
                Val::Bits(concrete_addr) => {
                    // 判死区域（W9）参与具体地址分派：访问与判死区域重叠直接
                    // BadRead 判死该路径，不查内容、不发事件。
                    if excluded_concrete_hit(&self.regions, concrete_addr.lower_u64(), bytes) {
                        return Err(ExecError::BadRead("excluded memory region"));
                    }
                    for region in &self.regions {
                        match region {
                            Region::Constrained(range, generator) if range.contains(&concrete_addr.lower_u64()) => {
                                if !opts.is_ifetch
                                    && self.client_info.as_ref().is_some_and(|client| client.handles_concrete_reads())
                                {
                                    if concrete_addr.lower_u64() != range.start
                                        || u64::from(bytes) != range.end - range.start
                                    {
                                        return Err(ExecError::BadRead(
                                            "Constrained read address is not within bounds",
                                        ));
                                    }
                                    return self.read_symbolic(
                                        read_kind,
                                        address,
                                        bytes,
                                        solver,
                                        tag,
                                        opts,
                                        region.region_name(),
                                    );
                                }
                                return read_constrained(
                                    range,
                                    generator.as_ref(),
                                    read_kind,
                                    concrete_addr.lower_u64(),
                                    address,
                                    bytes,
                                    solver,
                                    tag,
                                    opts,
                                    region.region_name(),
                                );
                            }

                            Region::Symbolic(range) if range.contains(&concrete_addr.lower_u64()) => {
                                return self.read_symbolic(
                                    read_kind,
                                    address,
                                    bytes,
                                    solver,
                                    tag,
                                    opts,
                                    region.region_name(),
                                )
                            }

                            Region::SymbolicCode(range) if range.contains(&concrete_addr.lower_u64()) => {
                                return self.read_symbolic(
                                    read_kind,
                                    address,
                                    bytes,
                                    solver,
                                    tag,
                                    opts,
                                    region.region_name(),
                                )
                            }

                            Region::Concrete(range, contents) if range.contains(&concrete_addr.lower_u64()) => {
                                if !opts.is_ifetch
                                    && self.client_info.as_ref().is_some_and(|client| client.handles_concrete_reads())
                                {
                                    return self.read_symbolic(
                                        read_kind,
                                        address,
                                        bytes,
                                        solver,
                                        tag,
                                        opts,
                                        region.region_name(),
                                    );
                                }
                                return read_concrete(
                                    contents,
                                    read_kind,
                                    concrete_addr.lower_u64(),
                                    address,
                                    bytes,
                                    solver,
                                    tag,
                                    opts,
                                    region.region_name(),
                                );
                            }

                            Region::Custom(range, contents) if range.contains(&concrete_addr.lower_u64()) => {
                                return contents.read(read_kind, concrete_addr.lower_u64(), bytes, solver, tag)
                            }

                            _ => continue,
                        }
                    }

                    if opts.is_ifetch {
                        Err(ExecError::BadRead("Attempted to fetch instruction from default memory"))
                    } else {
                        self.read_symbolic(read_kind, address, bytes, solver, tag, opts, DEFAULT_REGION_NAME)
                    }
                }

                Val::Symbolic(symbolic_addr) => {
                    // 自约束回调接管普通读；设备独立分派，Constrained 保留整区域读取合同。
                    let callback_reads = !opts.is_ifetch
                        && self.client_info.as_ref().is_some_and(|client| client.constrains_symbolic_reads());
                    // 低 64 位投影只用于区域分派，符号读事件保留完整的原始地址。
                    match self.check_concrete_overlap(
                        symbolic_addr,
                        bytes,
                        ExecError::SymbolicLength(
                            if tag { "read_memt_address" } else { "read_mem_address" },
                            SourceLoc::unknown(),
                        ),
                        |region| {
                            if callback_reads {
                                matches!(region, Region::Custom(..))
                                    || matches!(region, Region::Constrained(..))
                                        && !self.client_info.as_ref().unwrap().handles_concrete_reads()
                            } else {
                                !matches!(region, Region::Symbolic(_) | Region::SymbolicCode(_))
                            }
                        },
                        solver,
                    )? {
                        Overlap::Unique(concrete_addr) => {
                            if excluded_concrete_hit(&self.regions, concrete_addr, bytes) {
                                return Err(ExecError::BadRead("excluded memory region"));
                            }
                            for region in &self.regions {
                                match region {
                                    Region::Constrained(range, generator) if range.contains(&concrete_addr) => {
                                        if !opts.is_ifetch
                                            && self
                                                .client_info
                                                .as_ref()
                                                .is_some_and(|client| client.handles_concrete_reads())
                                        {
                                            if concrete_addr != range.start
                                                || u64::from(bytes) != range.end - range.start
                                            {
                                                return Err(ExecError::BadRead(
                                                    "Constrained read address is not within bounds",
                                                ));
                                            }
                                            return self.read_symbolic(
                                                read_kind,
                                                address,
                                                bytes,
                                                solver,
                                                tag,
                                                opts,
                                                region.region_name(),
                                            );
                                        }
                                        return read_constrained(
                                            range,
                                            generator.as_ref(),
                                            read_kind,
                                            concrete_addr,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        );
                                    }
                                    Region::Symbolic(range) | Region::SymbolicCode(range)
                                        if range.contains(&concrete_addr) =>
                                    {
                                        return self.read_symbolic(
                                            read_kind,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        )
                                    }
                                    Region::Concrete(range, contents) if range.contains(&concrete_addr) => {
                                        if callback_reads
                                            && self
                                                .client_info
                                                .as_ref()
                                                .is_some_and(|client| client.handles_concrete_reads())
                                        {
                                            return self.read_symbolic(
                                                read_kind,
                                                address,
                                                bytes,
                                                solver,
                                                tag,
                                                opts,
                                                region.region_name(),
                                            );
                                        }
                                        return read_concrete(
                                            contents,
                                            read_kind,
                                            concrete_addr,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        );
                                    }
                                    Region::Custom(range, contents) if range.contains(&concrete_addr) => {
                                        return contents.read(read_kind, concrete_addr, bytes, solver, tag)
                                    }
                                    _ => continue,
                                }
                            }
                            panic!("唯一重叠地址必须属于已定义区域");
                        }
                        Overlap::NoOverlap => {}
                    }
                    let info = SourceLoc::unknown();
                    let width = solver.length(symbolic_addr).expect("读地址必须是位向量");
                    let cmp_width = 64;
                    let addr_exp = if width > cmp_width {
                        Exp::Extract(63, 0, Box::new(Exp::Var(symbolic_addr)))
                    } else if width < cmp_width {
                        Exp::ZeroExtend(cmp_width - width, Box::new(Exp::Var(symbolic_addr)))
                    } else {
                        Exp::Var(symbolic_addr)
                    };
                    let mut unmatched = Exp::Bool(true);
                    for region in &self.regions {
                        if matches!(region, Region::Excluded(_)) {
                            continue;
                        }
                        let range = region.region_range();
                        let in_region = Exp::And(
                            Box::new(Exp::Bvule(Box::new(bits64(range.start, cmp_width)), Box::new(addr_exp.clone()))),
                            Box::new(Exp::Bvult(Box::new(addr_exp.clone()), Box::new(bits64(range.end, cmp_width)))),
                        );
                        // 沿用具体地址的区域优先级，证明所有候选都由同一区域处理。
                        let selected = Exp::And(Box::new(unmatched.clone()), Box::new(in_region.clone()));
                        let array_constrained = matches!(region, Region::Constrained(..))
                            && callback_reads
                            && self.client_info.as_ref().unwrap().handles_concrete_reads();
                        if array_constrained {
                            let valid = Exp::And(
                                Box::new(Exp::Bool(u64::from(bytes) == range.end - range.start)),
                                Box::new(Exp::Eq(Box::new(addr_exp.clone()), Box::new(bits64(range.start, 64)))),
                            );
                            let invalid = Exp::And(Box::new(selected.clone()), Box::new(Exp::Not(Box::new(valid))));
                            if solver.check_sat_with(&invalid, info).is_sat()? {
                                if solver.check_sat_with(&Exp::Not(Box::new(invalid)), info).is_unsat()? {
                                    return Err(ExecError::BadRead("Constrained read address is not within bounds"));
                                }
                                return Err(ExecError::SymbolicLength(
                                    if tag { "read_memt_address" } else { "read_mem_address" },
                                    info,
                                ));
                            }
                        }
                        if (array_constrained
                            || matches!(region, Region::Symbolic(_) | Region::SymbolicCode(_))
                            || matches!(region, Region::Concrete(..))
                                && !opts.is_ifetch
                                && self.client_info.as_ref().is_some_and(|client| client.handles_concrete_reads()))
                            && solver.check_sat_with(&Exp::Not(Box::new(selected)), info).is_unsat()?
                        {
                            return self.read_symbolic(
                                read_kind,
                                address,
                                bytes,
                                solver,
                                tag,
                                opts,
                                region.region_name(),
                            );
                        }
                        unmatched = Exp::And(Box::new(unmatched), Box::new(Exp::Not(Box::new(in_region))));
                    }
                    if !opts.is_ifetch
                        && self.client_info.as_ref().is_some_and(|client| client.constrains_symbolic_reads())
                    {
                        // 普通读的地址与内容由自约束回调处理，具体区域不能截获符号写后读。
                        return self.read_symbolic(read_kind, address, bytes, solver, tag, opts, DEFAULT_REGION_NAME);
                    }
                    // 跨区域候选复用地址拆分重试；唯一低位投影用于区域分派。
                    // 取指仍须经过区域检查，不能把合法代码区当成默认内存。
                    match self.check_concrete_overlap(
                        symbolic_addr,
                        bytes,
                        ExecError::SymbolicLength(if tag { "read_memt_address" } else { "read_mem_address" }, info),
                        |_| true,
                        solver,
                    )? {
                        Overlap::Unique(concrete_addr) => {
                            if excluded_concrete_hit(&self.regions, concrete_addr, bytes) {
                                return Err(ExecError::BadRead("excluded memory region"));
                            }
                            for region in &self.regions {
                                match region {
                                    Region::Constrained(range, generator) if range.contains(&concrete_addr) => {
                                        return read_constrained(
                                            range,
                                            generator.as_ref(),
                                            read_kind,
                                            concrete_addr,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        )
                                    }
                                    Region::Symbolic(range) | Region::SymbolicCode(range)
                                        if range.contains(&concrete_addr) =>
                                    {
                                        return self.read_symbolic(
                                            read_kind,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        )
                                    }
                                    Region::Concrete(range, contents) if range.contains(&concrete_addr) => {
                                        return read_concrete(
                                            contents,
                                            read_kind,
                                            concrete_addr,
                                            address,
                                            bytes,
                                            solver,
                                            tag,
                                            opts,
                                            region.region_name(),
                                        )
                                    }
                                    Region::Custom(range, contents) if range.contains(&concrete_addr) => {
                                        return contents.read(read_kind, concrete_addr, bytes, solver, tag)
                                    }
                                    _ => continue,
                                }
                            }
                            panic!("唯一重叠地址必须属于已定义区域");
                        }
                        Overlap::NoOverlap if opts.is_ifetch => {
                            Err(ExecError::BadRead("Attempted to fetch instruction from default memory"))
                        }
                        Overlap::NoOverlap => {
                            self.read_symbolic(read_kind, address, bytes, solver, tag, opts, DEFAULT_REGION_NAME)
                        }
                    }
                }

                _ => Err(ExecError::Type("Non bitvector address in read".to_string(), SourceLoc::unknown())),
            }
        } else {
            Err(ExecError::SymbolicLength("read_symbolic", SourceLoc::unknown()))
        }
    }

    pub fn write(
        &mut self,
        write_kind: Val<B>,
        address: Val<B>,
        data: Val<B>,
        solver: &mut Solver<B>,
        tag: Option<Val<B>>,
        opts: WriteOpts,
    ) -> Result<Val<B>, ExecError> {
        log!(log::MEMORY, &format!("Write: {:?} {:?} {:?} {:?}", write_kind, address, data, tag));

        match address {
            Val::Bits(concrete_addr) => {
                // 判死区域（W9）参与具体地址分派：访问与判死区域重叠直接
                // BadWrite 判死该路径，不写数组、不发事件。
                let bytes = data_bytes(&data, solver)?;
                if excluded_concrete_hit(&self.regions, concrete_addr.lower_u64(), bytes) {
                    return Err(ExecError::BadWrite("excluded memory region"));
                }
                for region in self.regions.iter_mut() {
                    match region {
                        Region::Custom(range, contents) if range.contains(&concrete_addr.lower_u64()) => {
                            return contents.write(write_kind, concrete_addr.lower_u64(), data, solver, tag)
                        }

                        Region::Excluded(_) => continue,
                        _ if region.region_range().contains(&concrete_addr.lower_u64()) => break,
                        _ => continue,
                    }
                }

                self.write_symbolic(write_kind, address, data, solver, tag, opts, DEFAULT_REGION_NAME)
            }

            Val::Symbolic(symbolic_addr) => {
                let callback_writes =
                    self.client_info.as_ref().is_some_and(|client| client.constrains_symbolic_writes());
                let bytes = data_bytes(&data, solver)?;
                match self.check_concrete_overlap(
                    symbolic_addr,
                    bytes,
                    ExecError::SymbolicLength(
                        if tag.is_some() { "write_memt_address" } else { "write_mem_address" },
                        SourceLoc::unknown(),
                    ),
                    |region| {
                        if callback_writes {
                            matches!(region, Region::Custom(..))
                        } else {
                            !matches!(region, Region::Symbolic(_) | Region::SymbolicCode(_))
                        }
                    },
                    solver,
                )? {
                    Overlap::Unique(concrete_addr) => {
                        if excluded_concrete_hit(&self.regions, concrete_addr, bytes) {
                            return Err(ExecError::BadWrite("excluded memory region"));
                        }
                        for region in self.regions.iter_mut() {
                            match region {
                                Region::Custom(range, contents) if range.contains(&concrete_addr) => {
                                    return contents.write(write_kind, concrete_addr, data, solver, tag)
                                }
                                Region::Excluded(_) => continue,
                                _ if region.region_range().contains(&concrete_addr) => break,
                                _ => continue,
                            }
                        }
                        // 低 64 位投影只用于区域分派，写事件必须保留完整符号地址。
                    }
                    Overlap::NoOverlap => {}
                }
                self.write_symbolic(write_kind, address, data, solver, tag, opts, DEFAULT_REGION_NAME)
            }

            _ => Err(ExecError::Type("Non bitvector address in write".to_string(), SourceLoc::unknown())),
        }
    }

    pub fn write_tag(
        &mut self,
        write_kind: Val<B>,
        address: Val<B>,
        tag: Val<B>,
        solver: &mut Solver<B>,
    ) -> Result<Val<B>, ExecError> {
        log!(log::MEMORY, &format!("Write tag: {:?} {:?} {:?}", write_kind, address, tag));

        self.write_symbolic_tag(write_kind, address, tag, solver)
    }

    /// The simplest read is to symbolically read a memory location. In
    /// that case we just return a fresh SMT bitvector of the appropriate
    /// size, and add a ReadMem event to the trace. For this we need the
    /// number of bytes to be non-symbolic.
    fn read_symbolic(
        &self,
        read_kind: Val<B>,
        address: Val<B>,
        bytes: u32,
        solver: &mut Solver<B>,
        tag: bool,
        opts: ReadOpts,
        region: &'static str,
    ) -> Result<Val<B>, ExecError> {
        let value = solver.declare_bitvector(8 * bytes, SourceLoc::unknown());
        let tag_value = if tag { Some(solver.declare_bitvector(1, SourceLoc::unknown())) } else { None };
        let tag_ir_value = tag_value.map(Val::Symbolic);
        let constrained = if let Some(c) = &self.client_info {
            c.symbolic_read(
                &self.regions,
                solver,
                &Val::Symbolic(value),
                &read_kind,
                &address,
                bytes,
                &tag_ir_value,
                &opts,
            )
        } else if self.regions.iter().any(|region| matches!(region, Region::Excluded(_))) {
            let addr_exp = crate::primop_util::smt_value(&address, SourceLoc::unknown())?;
            let not_overlap = smt_excluded_constraint(&self.regions, &addr_exp, bytes, solver)
                .expect("存在排除区域时必须生成排除约束");
            solver.add(Def::Assert(not_overlap));
            true
        } else {
            false
        };
        // W7：回调追加了读地址约束（W9 起即判死区域的 NOT 链）时立即检查可
        // 满足性。真实访存路径在读之前已先经模型侧 PMA/PMP 检查，其
        // range_subset 分支可能已把地址断言进判死区域内的 PMA 区间；不在此处
        // 判死的话路径会跑完整条指令、烧掉一次终值模型查询后才在 collector 被
        // 丢弃（W7 修复，端到端证据 /tmp/isla-memimpl-w6-1532/unsat_dump/）。
        if constrained && solver.check_sat(SourceLoc::unknown()).is_unsat()? {
            return Err(ExecError::BadRead("symbolic address falls in excluded memory region"));
        }
        solver.add_event(Event::ReadMem {
            value: Val::Symbolic(value),
            read_kind,
            address,
            bytes,
            tag_value: tag_ir_value.clone(),
            opts,
            region,
        });

        log!(log::MEMORY, &format!("Read symbolic: {} {:?}", value, tag_value));

        let return_value = match tag_ir_value {
            Some(v) => make_bv_bit_pair(Val::Symbolic(value), v),
            None => Val::Symbolic(value),
        };
        Ok(return_value)
    }

    /// `write_symbolic` just adds a WriteMem event to the trace,
    /// returning a symbolic boolean (the semantics of which is controlled
    /// by a memory model if required, but can be ignored in
    /// others). Raises a type error if the data argument is not a
    /// bitvector with a length that is a multiple of 8. This should be
    /// guaranteed by the Sail type system.
    fn write_symbolic(
        &mut self,
        write_kind: Val<B>,
        address: Val<B>,
        data: Val<B>,
        solver: &mut Solver<B>,
        tag: Option<Val<B>>,
        opts: WriteOpts,
        region: &'static str,
    ) -> Result<Val<B>, ExecError> {
        use crate::smt::smtlib::*;

        let bytes = data_bytes(&data, solver)?;

        let value = solver.fresh();
        solver.add(Def::DeclareConst(value, Ty::Bool));
        let constrained = if let Some(c) = &mut self.client_info {
            c.symbolic_write(&self.regions, solver, value, &write_kind, &address, &data, bytes, &tag, &opts)
        } else if self.regions.iter().any(|region| matches!(region, Region::Excluded(_))) {
            let addr_exp = crate::primop_util::smt_value(&address, SourceLoc::unknown())?;
            let not_overlap = smt_excluded_constraint(&self.regions, &addr_exp, bytes, solver)
                .expect("存在排除区域时必须生成排除约束");
            solver.add(Def::Assert(not_overlap));
            true
        } else {
            false
        };
        // W7：与读侧对称——回调追加了写地址约束（W9 起即判死区域的 NOT 链）
        // 时立即判死矛盾路径（见 `read_symbolic` 的 W7 注释）。
        if constrained && solver.check_sat(SourceLoc::unknown()).is_unsat()? {
            return Err(ExecError::BadWrite("symbolic address falls in excluded memory region"));
        }
        solver.add_event(Event::WriteMem { value, write_kind, address, data, bytes, tag_value: tag, opts, region });

        Ok(Val::Symbolic(value))
    }

    fn write_symbolic_tag(
        &mut self,
        write_kind: Val<B>,
        address: Val<B>,
        tag: Val<B>,
        solver: &mut Solver<B>,
    ) -> Result<Val<B>, ExecError> {
        use crate::smt::smtlib::*;

        let value = solver.fresh();
        solver.add(Def::DeclareConst(value, Ty::Bool));
        if let Some(c) = &mut self.client_info {
            c.symbolic_write_tag(&self.regions, solver, value, &write_kind, &address, &tag)
        };
        solver.add_event(Event::WriteMem {
            value,
            write_kind,
            address,
            data: Val::Bits(B::zero_width()),
            bytes: 0,
            tag_value: Some(tag),
            opts: WriteOpts::default(),
            region: DEFAULT_REGION_NAME,
        });

        Ok(Val::Symbolic(value))
    }

    pub fn smt_address_constraint(
        &self,
        address: &Exp<Sym>,
        bytes: u32,
        kind: SmtKind,
        solver: &mut Solver<B>,
        tag: Option<&Exp<Sym>>,
    ) -> Exp<Sym> {
        smt_address_constraint(&self.regions, address, bytes, kind, solver, tag)
    }

    // Perform a concrete version of the address constraint
    pub fn access_check(&self, address: Address, bytes: u32, kind: SmtKind) -> bool {
        access_check(&self.regions, address, bytes, kind)
    }
}

/// 访问起点已在区域内，或沿模地址空间到区域起点的距离小于访问长度，即触碰区域。
/// 这一判断等价于逐字节检查，且不会为超大访问长度线性枚举。
fn excluded_overlap(range: &Range<Address>, address: Address, bytes: u32) -> bool {
    bytes != 0
        && range.start < range.end
        && (range.contains(&address) || range.start.wrapping_sub(address) < u64::from(bytes))
}

/// 具体地址（读或写）是否落在任一判死区域内。
fn excluded_concrete_hit<B: BV>(regions: &[Region<B>], address: Address, bytes: u32) -> bool {
    regions.iter().any(|region| match region {
        Region::Excluded(range) => excluded_overlap(range, address, bytes),
        _ => false,
    })
}

/// 写数据的字节长度（位长必须是 8 的倍数，否则类型错误——与
/// `write_symbolic` 的既有检查一致，供具体地址分派复用）。
fn data_bytes<B: BV>(data: &Val<B>, solver: &mut Solver<B>) -> Result<u32, ExecError> {
    let data_length = crate::primop_util::length_bits(data, solver, SourceLoc::unknown())?;
    if data_length % 8 != 0 {
        return Err(ExecError::Type(format!("write_symbolic {:?}", &data_length), SourceLoc::unknown()));
    }
    Ok(data_length / 8)
}

fn ranges_for_access_checks<B: BV>(
    regions: &[Region<B>],
    bytes: u32,
    kind: SmtKind,
) -> impl Iterator<Item = (&Range<Address>, bool)> {
    regions
        .iter()
        .filter(move |r| match kind {
            SmtKind::ReadData => !matches!(r, Region::Excluded(_)),
            SmtKind::ReadInstr => matches!(r, Region::SymbolicCode(_)),
            SmtKind::WriteData => matches!(r, Region::Symbolic(_)),
        })
        .map(|r| (r.region_range(), matches!(r, Region::Symbolic(_))))
        .filter(move |(r, _k)| r.end - r.start >= bytes as u64)
}

pub fn access_check<B: BV>(regions: &[Region<B>], address: Address, bytes: u32, kind: SmtKind) -> bool {
    ranges_for_access_checks(regions, bytes, kind).any(|(r, _k)| r.start <= address && address <= r.end - bytes as u64)
}

pub fn smt_address_constraint<B: BV>(
    regions: &[Region<B>],
    address: &Exp<Sym>,
    bytes: u32,
    kind: SmtKind,
    solver: &mut Solver<B>,
    tag: Option<&Exp<Sym>>,
) -> Exp<Sym> {
    use crate::smt::smtlib::Exp::*;
    let addr_var = match address {
        Var(v) => *v,
        _ => {
            let v = solver.fresh();
            solver.add(Def::DefineConst(v, address.clone()));
            v
        }
    };
    let addr_size = solver.length(addr_var).unwrap_or_else(|| panic!("address is not a bitvector"));
    ranges_for_access_checks(regions, bytes, kind)
        .map(|(r, k)| {
            let in_range = And(
                Box::new(Bvule(Box::new(bits64(r.start, addr_size)), Box::new(Var(addr_var)))),
                // Use an extra bit to prevent wrapping
                Box::new(Bvule(
                    Box::new(Bvadd(
                        Box::new(ZeroExtend(1, Box::new(Var(addr_var)))),
                        Box::new(ZeroExtend(1, Box::new(bits64(bytes as u64, addr_size)))),
                    )),
                    Box::new(ZeroExtend(1, Box::new(bits64(r.end, addr_size)))),
                )),
            );
            // If we're not in a normal Symbolic region tags must be clear
            if let (false, Some(tag)) = (k, tag) {
                And(Box::new(in_range), Box::new(Eq(Box::new(tag.clone()), Box::new(bits64(0, 1)))))
            } else {
                in_range
            }
        })
        .fold(Bool(false), |acc, e| match acc {
            Bool(false) => e,
            _ => Or(Box::new(acc), Box::new(e)),
        })
}

/// 排除每个实际访问的字节，包括按地址位宽相加回绕后的字节。
/// 使用模距离表达逐字节重叠条件，不随 bytes 增长约束规模。
/// 区域仍按低 64 位地址匹配；没有排除区域时不加约束。
pub fn smt_excluded_constraint<B: BV>(
    regions: &[Region<B>],
    address: &Exp<Sym>,
    bytes: u32,
    solver: &mut Solver<B>,
) -> Option<Exp<Sym>> {
    use crate::smt::smtlib::Exp::*;
    if !regions.iter().any(|region| matches!(region, Region::Excluded(_))) {
        return None;
    }
    if bytes == 0 {
        return Some(Bool(true));
    }
    let addr_var = match address {
        Var(v) => *v,
        _ => solver.define_const(address.clone(), SourceLoc::unknown()),
    };
    let addr_size = solver.length(addr_var).expect("排除检查地址必须是位向量");
    assert!(addr_size > 0, "排除检查地址位宽必须为正");
    let cmp_size = addr_size.min(64);
    let addr_exp = if addr_size > 64 { Extract(63, 0, Box::new(Var(addr_var))) } else { Var(addr_var) };
    let region_addr =
        if cmp_size < 64 { ZeroExtend(64 - cmp_size, Box::new(addr_exp.clone())) } else { addr_exp.clone() };
    let domain_end = 1u128 << cmp_size;
    let mut allowed = Bool(true);
    for region in regions {
        let Region::Excluded(range) = region else { continue };
        // 窄地址空间无法命中域外区域，跨越域末端的区域只保留域内部分。
        let end = u128::from(range.end).min(domain_end);
        if u128::from(range.start) >= end {
            continue;
        }
        let in_range = And(
            Box::new(Bvule(Box::new(bits64(range.start, 64)), Box::new(region_addr.clone()))),
            Box::new(Bvult(Box::new(region_addr.clone()), Box::new(bits64(u64::try_from(end).unwrap(), 64)))),
        );
        let distance = Bvsub(Box::new(bits64(range.start, cmp_size)), Box::new(addr_exp.clone()));
        let distance = if cmp_size < 64 { ZeroExtend(64 - cmp_size, Box::new(distance)) } else { distance };
        // 起点在区域内，或某个字节回绕后首先触到区域起点。
        let overlap =
            Or(Box::new(in_range), Box::new(Bvult(Box::new(distance), Box::new(bits64(u64::from(bytes), 64)))));
        allowed = And(Box::new(allowed), Box::new(Not(Box::new(overlap))));
    }
    Some(allowed)
}

fn reverse_endianness(bytes: &mut [u8]) {
    if bytes.len() <= 2 {
        bytes.reverse()
    } else {
        let (bytes_upper, bytes_lower) = bytes.split_at_mut(bytes.len() / 2);
        reverse_endianness(bytes_upper);
        reverse_endianness(bytes_lower);
        bytes.rotate_left(bytes.len() / 2)
    }
}

#[allow(clippy::too_many_arguments)]
fn read_constrained<B: BV>(
    range: &Range<Address>,
    generator: &dyn Fn(&mut Solver<B>) -> Sym,
    read_kind: Val<B>,
    address: Address,
    event_address: Val<B>,
    bytes: u32,
    solver: &mut Solver<B>,
    tag: bool,
    opts: ReadOpts,
    region: &'static str,
) -> Result<Val<B>, ExecError> {
    let constrained = generator(solver);
    solver.mark_bitvector(constrained);
    if address == range.start && address + bytes as u64 == range.end {
        solver.add_event(Event::ReadMem {
            value: Val::Symbolic(constrained),
            read_kind,
            address: event_address,
            bytes,
            tag_value: None,
            opts,
            region,
        });
        if tag {
            Ok(make_bv_bit_pair(Val::Symbolic(constrained), Val::Bits(B::zeros(1))))
        } else {
            Ok(Val::Symbolic(constrained))
        }
    } else {
        Err(ExecError::BadRead("Constrained read address is not within bounds"))
    }
}

fn read_concrete<B: BV>(
    memory: &HashMap<Address, u8>,
    read_kind: Val<B>,
    address: Address,
    event_address: Val<B>,
    bytes: u32,
    solver: &mut Solver<B>,
    tag: bool,
    opts: ReadOpts,
    region: &'static str,
) -> Result<Val<B>, ExecError> {
    let mut byte_vec: Vec<u8> = Vec::with_capacity(bytes as usize);
    for i in address..(address + u64::from(bytes)) {
        byte_vec.push(*memory.get(&i).unwrap_or(&0))
    }

    reverse_endianness(&mut byte_vec);

    if byte_vec.len() <= 8 {
        log!(log::MEMORY, &format!("Read concrete: {:?}", byte_vec));

        let value = Val::Bits(B::from_bytes(&byte_vec));
        solver.add_event(Event::ReadMem {
            value,
            read_kind,
            address: event_address,
            bytes,
            tag_value: None,
            opts,
            region,
        });
        if tag {
            Ok(make_bv_bit_pair(Val::Bits(B::from_bytes(&byte_vec)), Val::Bits(B::zeros(1))))
        } else {
            Ok(Val::Bits(B::from_bytes(&byte_vec)))
        }
    } else {
        // TODO: Handle reads > 64 bits
        Err(ExecError::BadRead("Concrete read more than 8 bytes"))
    }
}

